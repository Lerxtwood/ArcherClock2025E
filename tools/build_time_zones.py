"""Generate the firmware's time zone table from a Python tzdata wheel."""

import argparse
from datetime import datetime, timedelta, timezone
from io import BytesIO
from pathlib import Path
import struct
from zipfile import ZipFile
from zoneinfo import ZoneInfo


FIRST_YEAR = 2024
LAST_YEAR = 2099
UTC = timezone.utc
EPOCH = datetime(FIRST_YEAR, 1, 1, tzinfo=UTC)
START = int(EPOCH.timestamp())
END = int(datetime(LAST_YEAR + 1, 1, 1, tzinfo=UTC).timestamp())
DAY = 24 * 60 * 60


def explicit_transitions(tzif):
    """Read the 64-bit transition timestamps from a TZif v2 or later file."""
    ut, std, leaps, times, types, chars = struct.unpack_from(">6I", tzif, 20)
    second_header = 44 + 5 * times + 6 * types + chars + 8 * leaps + std + ut
    count = struct.unpack_from(">I", tzif, second_header + 32)[0]
    return struct.unpack_from(f">{count}q", tzif, second_header + 44)


def schedule(tzif, irish_time):
    zone = ZoneInfo.from_file(BytesIO(tzif))

    def state(timestamp):
        local = datetime.fromtimestamp(timestamp, UTC).astimezone(zone)
        offset = local.utcoffset()
        minutes, seconds = divmod(int(offset.total_seconds()), 60)
        if seconds:
            raise ValueError(f"Sub-minute offset at {local.isoformat()}")
        # The Irish legal definition uses summer as standard time. The UI uses
        # the usual winter/summer meanings of standard and daylight time.
        daylight = offset > timedelta(0) if irish_time else bool(local.dst())
        return minutes, daylight

    result = [(START, *state(START))]

    def add(timestamp):
        current = state(timestamp)
        if current != result[-1][1:]:
            result.append((timestamp, *current))

    explicit = explicit_transitions(tzif)
    for timestamp in explicit:
        if START < timestamp < END:
            add(timestamp)

    # Beyond the file's last explicit transition, ZoneInfo applies the TZif
    # footer's recurring rules. Locate each change down to the exact second.
    left = max(START, explicit[-1] if explicit else START)
    while left < END - 1:
        right = min(left + DAY, END - 1)
        if state(right) != result[-1][1:]:
            low, high = left, right
            while high - low > 1:
                middle = (low + high) // 2
                if state(middle) == result[-1][1:]:
                    low = middle
                else:
                    high = middle
            add(high)
        left = right
    return tuple(result)


def generate(wheel):
    with ZipFile(wheel) as archive:
        prefix = "tzdata/zoneinfo/"
        version = archive.read(prefix + "tzdata.zi").splitlines()[0].decode().split()[-1]
        names = sorted(archive.read("tzdata/zones").decode().splitlines())
        irish_tzif = archive.read(prefix + "Europe/Dublin")
        schedules_by_file = {}
        schedule_ids = {}
        zones = []
        for name in names:
            tzif = archive.read(prefix + name)
            if tzif not in schedules_by_file:
                schedules_by_file[tzif] = schedule(tzif, tzif == irish_tzif)
            transitions = schedules_by_file[tzif]
            if transitions not in schedule_ids:
                schedule_ids[transitions] = len(schedule_ids)
            zones.append((name, schedule_ids[transitions]))

    yield f"// Generated by tools/build_time_zones.py from IANA tzdata {version} (public domain)."
    yield f"// UTC offsets and daylight saving transitions for {FIRST_YEAR}–{LAST_YEAR}."
    yield f"constexpr uint32_t FIRST_TIME_ZONE_TIMESTAMP = {START}u;"
    yield ""
    yield "constexpr TimeZoneTransition TIME_ZONE_TRANSITIONS[] = {"
    for identifier, transitions in enumerate(schedule_ids):
        yield f"  // Schedule {identifier}"
        for timestamp, minutes, daylight in transitions:
            yield f"  {{{timestamp}u, {minutes}, {str(daylight).lower()}}},"
    yield "};"
    yield ""
    yield "constexpr TimeZoneSchedule TIME_ZONE_SCHEDULES[] = {"
    start = 0
    for transitions in schedule_ids:
        yield f"  {{{start}, {len(transitions)}}},"
        start += len(transitions)
    yield "};"
    yield ""
    yield "constexpr TimeZone TIME_ZONES[] = {"
    for name, index in zones:
        yield f'  {{"{name}", {index}}},'
    yield "};"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("wheel", type=Path, help="Path to a tzdata wheel")
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / "src" / "time_zones_data.inc"
    output.write_text("\n".join(generate(args.wheel)) + "\n", encoding="utf-8", newline="\n")
